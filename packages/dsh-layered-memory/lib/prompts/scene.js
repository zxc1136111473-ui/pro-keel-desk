function formatSceneSummaries(scenes) {
  if (scenes.length === 0) return "\uFF08\u5F53\u524D\u65E0\u573A\u666F\u6587\u4EF6\uFF09";
  const head = `\u5F53\u524D\u573A\u666F\u603B\u6570\uFF1A${scenes.length}`;
  const rows = scenes.map(
    (s) => `- \`${s.path}\` | heat=${s.heat} | updated=${s.updated} | ${s.summary || "(\u65E0\u6458\u8981)"}`
  );
  return `${head}
${rows.join("\n")}`;
}
